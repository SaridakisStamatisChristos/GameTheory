"""Bounded exact vertex enumeration and affine dimension of Nash-cell closures.

Given a strict-support polytope with a strictly positive feasible witness,
its topological closure is obtained by relaxing support p_i > 0 to p_i >= 0.
The vertex set of this closed bounded rational polytope is finite.
"""
from fractions import Fraction
from itertools import combinations
from math import comb


class VertexBudgetExceeded(ValueError):
    """Exact vertex candidate limit was reached; no partial result is certified."""


def _rank(matrix):
    """Exact rational coefficient rank, independent of RHS consistency."""
    if not matrix:
        return 0
    a = [list(map(Fraction, row)) for row in matrix]
    n = len(a[0])
    pivot_row = 0
    for col in range(n):
        pivot = next((i for i in range(pivot_row, len(a)) if a[i][col]), None)
        if pivot is None:
            continue
        a[pivot_row], a[pivot] = a[pivot], a[pivot_row]
        d = a[pivot_row][col]
        a[pivot_row] = [v / d for v in a[pivot_row]]
        for row in range(pivot_row + 1, len(a)):
            if a[row][col]:
                q = a[row][col]
                a[row] = [x - q*y for x,y in zip(a[row],a[pivot_row])]
        pivot_row += 1
        if pivot_row == len(a):
            break
    return pivot_row


def _solve_square(matrix, rhs):
    """Exact Gauss-Jordan solution; singular candidate bases are rejected."""
    n = len(rhs)
    a = [list(row) + [value] for row, value in zip(matrix, rhs)]
    for col in range(n):
        pivot = next((r for r in range(col,n) if a[r][col]), None)
        if pivot is None:
            return None
        a[col], a[pivot] = a[pivot], a[col]
        d = a[col][col]
        a[col] = [x/d for x in a[col]]
        for r in range(n):
            if r != col and a[r][col]:
                q = a[r][col]
                a[r] = [v - q*w for v,w in zip(a[r],a[col])]
    return tuple(row[-1] for row in a)


def enumerate_polytope_vertices(polytope, budget, *, allow_empty=False):
    """Return exact vertices of closure and its affine dimension.

    The input is a validated, **nonempty strict-support** Nash polytope
    generated by exact_nash_set._player_polytope. Its closure is the same
    as the weak-inequality feasible region by convex interpolation with
    the strictly positive witness.
    """
    k = len(polytope['variable_actions'])
    eq = [(tuple([Fraction(1)]*k),Fraction(1))]
    for record in polytope['equalities_dot_coefficients_eq_zero']:
        eq.append((tuple(Fraction(t) for t in record['coefficients_exact']),Fraction(0)))
    inequalities = []
    for i in range(k):
        inequalities.append((tuple(Fraction(int(i==j)) for j in range(k)),Fraction(0)))
    for record in polytope['inequalities_dot_coefficients_ge_zero']:
        inequalities.append((tuple(Fraction(t) for t in record['coefficients_exact']),Fraction(0)))
    # Remove proportional duplicate active half-spaces only when identical.
    inequalities = list(dict.fromkeys(inequalities))
    independent = []
    for row in eq:
        if _rank([v[0] for v in independent]+[row[0]]) > len(independent):
            independent.append(row)
    needed = k - len(independent)
    # Rank never exceeds k, and the k positivity bounds provide enough
    # candidate active inequalities even for lower-dimensional polytopes.
    # A bounded polytope always has vertices, including when lower-dimensional.
    count = comb(len(inequalities), needed)
    if budget['tested'] + count > budget['limit']:
        raise VertexBudgetExceeded('Exact vertex candidate budget exceeded')
    vertices = set()
    for selected in combinations(inequalities,needed):
        budget['tested'] += 1
        constraints = independent + list(selected)
        solution = _solve_square([row for row,_ in constraints], [v for _,v in constraints])
        if solution is None:
            continue
        if not all(sum(c*x for c,x in zip(row,solution))==rhs for row,rhs in eq):
            continue
        if not all(sum(c*x for c,x in zip(row,solution))>=rhs for row,rhs in inequalities):
            continue
        vertices.add(solution)
    if not vertices:
        if allow_empty:
            return None
        raise AssertionError('Nonempty bounded rational polytope returned no vertices')
    ordered=sorted(vertices)
    dimension = _rank([tuple(a-b for a,b in zip(v,ordered[0])) for v in ordered[1:]])
    return {
        'closure_vertices_exact': [[str(x) for x in v] for v in ordered],
        'affine_dimension': dimension,
        'vertex_semantics': 'vertices of the closure; some may lie outside the strict-support cell',
    }
